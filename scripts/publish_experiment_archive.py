"""Create verified ZIP volumes and publish them to this repository's release.

Uses the already authenticated Git Credential Manager account, never stores its
credential, never deletes source data. Restarting resumes completed volumes and
already uploaded assets. Output goes to ignored var/github-publication.
"""
from __future__ import annotations

import concurrent.futures
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import threading
import time
import zipfile

ROOT = Path(__file__).resolve().parents[1]
DATA_ROOT = Path("\\\\?\\" + str(ROOT)) if os.name == "nt" else ROOT
OUT = ROOT / "var/github-publication"
TAG = "experiments-2026-10-24"
REPO = "THANHTAI2004/Smart_Retail_Floor_Allocation"
GH = ROOT / "var/github-tools/gh/bin/gh.exe"
LOCK = threading.Lock()
STATE: dict = {}
SECRET = re.compile(rb"(?:gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{30,}|-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----|mongodb(?:\+srv)?://[^\s/:<>\"']+:[^\s@<>\"']+@)")


def save_state(**updates):
    with LOCK:
        STATE.update(updates, updated_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()))
        temp = OUT / "status.tmp"
        temp.write_text(json.dumps(STATE, indent=2), encoding="utf-8")
        for attempt in range(100):
            try:
                os.replace(temp, OUT / "status.json")
                break
            except PermissionError:
                if attempt == 99:
                    raise
                time.sleep(0.05)


def digest(path):
    h = hashlib.sha256()
    with path.open("rb") as f:
        for data in iter(lambda: f.read(8 * 1024 * 1024), b""):
            h.update(data)
    return h.hexdigest()


def gh(args, env, check=True):
    p = subprocess.run([str(GH), *args], cwd=ROOT, env=env,
                       capture_output=True, text=True, encoding="utf-8")
    if check and p.returncode:
        raise RuntimeError(f"gh {args[0]} failed: {p.stderr[:1500]}")
    return p


def inventory():
    rows, excluded = [], []
    def walk_error(error):
        raise error
    for base, dirs, files in os.walk(DATA_ROOT / "experiments", followlinks=False, onerror=walk_error):
        retained_dirs = []
        for name in sorted(dirs):
            folder = Path(base) / name
            if name in {"__pycache__", ".pytest_cache", ".venv", "node_modules"}:
                excluded.append({"path": folder.relative_to(DATA_ROOT).as_posix(), "reason": "generated environment/cache directory"})
            elif folder.is_symlink() or folder.is_junction():
                excluded.append({"path": folder.relative_to(DATA_ROOT).as_posix(), "reason": "filesystem alias", "target": os.readlink(folder)})
            else:
                retained_dirs.append(name)
        dirs[:] = retained_dirs
        for name in sorted(files):
            path = Path(base) / name
            rel = path.relative_to(DATA_ROOT).as_posix()
            if path.is_symlink() or path.is_junction():
                excluded.append({"path": rel, "reason": "filesystem alias", "target": os.readlink(path)})
                continue
            if (name.startswith(".env") and name != ".env.example") or name.lower().endswith((".pem", ".key", ".pyc", ".pyo")) or name.lower() == "private.json":
                excluded.append({"path": rel, "reason": "private configuration/key or generated bytecode"})
                continue
            st = path.stat()
            rows.append({"path": rel, "size": st.st_size, "mtime_ns": st.st_mtime_ns})
            if len(rows) % 25000 == 0:
                save_state(status="INVENTORY", inventoried_files=len(rows))
    # Bounded uncompressed size also bounds the ZIP size below GitHub's 2 GiB.
    groups, group, size = [], [], 0
    for row in rows:
        if row["size"] > 1900 * 1024**2:
            raise RuntimeError(f"Single input requires splitting: {row['path']}")
        if group and (size + row["size"] > 1024**3 or len(group) >= 20000):
            groups.append(group)
            group, size = [], 0
        group.append(row)
        size += row["size"]
    if group:
        groups.append(group)
    snapshot = {"created_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                "files": len(rows), "bytes": sum(r["size"] for r in rows),
                "excluded": excluded, "groups": groups}
    (OUT / "inventory.json").write_text(json.dumps(snapshot), encoding="utf-8")
    return snapshot


def make_volume(item):
    number, rows = item
    name = f"experiments-{number:04d}.zip"
    path, receipt = OUT / name, OUT / f"{name}.json"
    if path.exists() and receipt.exists():
        result = json.loads(receipt.read_text(encoding="utf-8"))
        if path.stat().st_size == result["bytes"] and digest(path) == result["sha256"]:
            return result
        raise RuntimeError(f"Existing archive checksum mismatch: {name}")
    manifest = []
    # A ZIP records the actual bytes read, even when a live operational log grows.
    # Scientific results are immutable; changed operational files are identified.
    with zipfile.ZipFile(path.with_suffix(".zip.partial"), "w", zipfile.ZIP_DEFLATED,
                         compresslevel=1, allowZip64=True) as archive:
        for row in rows:
            source = DATA_ROOT / row["path"]
            before = source.stat()
            h, size, tail = hashlib.sha256(), 0, b""
            scan = source.suffix.lower() in {".json", ".jsonl", ".txt", ".py", ".ps1", ".yaml", ".yml", ".toml", ".ini", ".cfg", ".md", ".csv", ".log", ".xml"}
            with source.open("rb") as f, archive.open(row["path"], "w", force_zip64=True) as dest:
                # Bound live logs to their start size so the snapshot is finite.
                remaining = before.st_size
                while remaining:
                    data = f.read(min(1024 * 1024, remaining))
                    if not data:
                        raise RuntimeError(f"Source truncated during snapshot: {row['path']}")
                    if scan and SECRET.search(tail + data):
                        raise RuntimeError(f"Potential credential in {row['path']}; publication stopped")
                    tail = data[-256:]
                    h.update(data)
                    size += len(data)
                    remaining -= len(data)
                    dest.write(data)
            after = source.stat()
            changed = (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns)
            if changed and row["path"].startswith("experiments/results/"):
                raise RuntimeError(f"Scientific result changed during archive: {row['path']}")
            manifest.append({"path": row["path"], "bytes": size, "sha256": h.hexdigest(),
                             "live_file_changed": changed})
        archive.writestr("ARCHIVE_CONTENTS.json", json.dumps(manifest, ensure_ascii=False))
    os.replace(path.with_suffix(".zip.partial"), path)
    # Independently decompress every member and replay its expected SHA256.
    with zipfile.ZipFile(path) as archive:
        for record in manifest:
            h = hashlib.sha256()
            with archive.open(record["path"]) as f:
                for data in iter(lambda: f.read(1024 * 1024), b""):
                    h.update(data)
            if h.hexdigest() != record["sha256"]:
                raise RuntimeError(f"Archive replay mismatch: {record['path']}")
    result = {"name": name, "bytes": path.stat().st_size, "sha256": digest(path),
              "files": len(rows), "uncompressed_bytes": sum(r["bytes"] for r in manifest),
              "changed_live_files": [r["path"] for r in manifest if r["live_file_changed"]]}
    if result["bytes"] >= 2 * 1024**3:
        raise RuntimeError(f"Archive exceeds GitHub asset limit: {name}")
    receipt.write_text(json.dumps(result, indent=2), encoding="utf-8")
    return result


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    save_state(status="INVENTORY", release_tag=TAG, repository=REPO)
    inv_path = OUT / "inventory.json"
    inv = json.loads(inv_path.read_text(encoding="utf-8")) if inv_path.exists() else inventory()
    save_state(status="ARCHIVING", files=inv["files"], source_bytes=inv["bytes"],
               total_volumes=len(inv["groups"]), archived_volumes=0, uploaded_volumes=0)
    credential = subprocess.run(["git", "credential", "fill"],
        input="protocol=https\nhost=github.com\n\n", capture_output=True, text=True, check=True)
    values = dict(line.split("=", 1) for line in credential.stdout.splitlines() if "=" in line)
    env = os.environ.copy()
    env["GH_TOKEN"] = values["password"]
    login = gh(["api", "user", "--jq", ".login"], env).stdout.strip()
    if login != "THANHTAI2004":
        raise RuntimeError("Authenticated GitHub account does not match requested owner")
    # The release is published only after all assets are independently verified.
    view = gh(["release", "view", TAG, "--repo", REPO, "--json", "isDraft"], env, check=False)
    if view.returncode:
        gh(["release", "create", TAG, "--repo", REPO, "--target", "main", "--draft",
            "--title", "Complete experiment archive - 2026-10-24", "--notes",
            "Full experiment snapshot. Download every ZIP and extract into the repository root. SHA256SUMS and ARCHIVE_MANIFEST.json describe all volumes; each ZIP includes per-file SHA256 checksums. No numerical jobs are rerun by this publication."], env)
    results = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
        for result in pool.map(make_volume, enumerate(inv["groups"], 1)):
            results.append(result)
            save_state(archived_volumes=len(results), archived_bytes=sum(r["bytes"] for r in results))
            print(json.dumps({"archived": result["name"], "files": result["files"], "bytes": result["bytes"]}), flush=True)
    manifest = {k: v for k, v in inv.items() if k != "groups"}
    manifest.update(volumes=results, source_commit=subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
                    extraction="Extract all experiments-*.zip into the cloned repository root; every ZIP is independent.",
                    snapshot_semantics="Membership fixed at inventory time; live logs bounded at read-start size; each ZIP records actual file hashes. Numerical results must remain unchanged.")
    (OUT / "ARCHIVE_MANIFEST.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    (OUT / "SHA256SUMS").write_text("".join(f"{r['sha256']}  {r['name']}\n" for r in results), encoding="ascii")
    save_state(status="UPLOADING")
    for i, result in enumerate(results, 1):
        # A digest match is required before skipping an existing uploaded asset.
        assets = json.loads(gh(["api", f"repos/{REPO}/releases/tags/{TAG}"], env).stdout)["assets"]
        existing = next((a for a in assets if a["name"] == result["name"]), None)
        expected = "sha256:" + result["sha256"]
        if existing and (existing.get("digest") != expected or existing["size"] != result["bytes"]):
            raise RuntimeError(f"Remote existing asset differs: {result['name']}")
        if not existing:
            for attempt in range(4):
                upload = gh(["release", "upload", TAG, str(OUT / result["name"]), "--repo", REPO], env, check=False)
                if not upload.returncode:
                    break
                if attempt == 3:
                    raise RuntimeError(f"Upload failed: {result['name']}: {upload.stderr[:1000]}")
                time.sleep(5)
        save_state(uploaded_volumes=i)
        print(json.dumps({"uploaded": result["name"], "count": i}), flush=True)
    gh(["release", "upload", TAG, str(OUT / "SHA256SUMS"), str(OUT / "ARCHIVE_MANIFEST.json"), "--repo", REPO, "--clobber"], env)
    remote = json.loads(gh(["api", f"repos/{REPO}/releases/tags/{TAG}"], env).stdout)
    by_name = {a["name"]: a for a in remote["assets"]}
    for result in results:
        asset = by_name[result["name"]]
        if asset.get("digest") != "sha256:" + result["sha256"] or asset["size"] != result["bytes"]:
            raise RuntimeError(f"Remote digest verification failed: {result['name']}")
    for name in ("SHA256SUMS", "ARCHIVE_MANIFEST.json"):
        if by_name[name].get("digest") != "sha256:" + digest(OUT / name):
            raise RuntimeError(f"Remote digest verification failed: {name}")
    gh(["release", "edit", TAG, "--repo", REPO, "--draft=false"], env)
    save_state(status="COMPLETE", remote_assets=len(remote["assets"]),
               release_url=f"https://github.com/{REPO}/releases/tag/{TAG}")


if __name__ == "__main__":
    try:
        main()
    except BaseException as exc:
        save_state(status="ERROR", error=str(exc))
        raise
